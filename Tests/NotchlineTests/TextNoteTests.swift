import AppKit
import XCTest
@testable import Notchline

final class TextNoteTests: XCTestCase {
    @MainActor
    func testStartupDefaultsRespectEachDisabledOption() throws {
        let suite = "NotchlineTests." + UUID().uuidString
        let defaults = try XCTUnwrap(UserDefaults(suiteName: suite))
        defer { defaults.removePersistentDomain(forName: suite) }
        let keys = ["clipboardEnabled", "clipboardTextEnabled", "randomPaperColors"]
        for disabled in keys {
            defaults.setPersistentDomain([disabled: false], forName: suite)
            defaults.register(defaults: ClipboardWatcher.defaultPreferences)
            for key in keys {
                XCTAssertEqual(defaults.bool(forKey: key), key != disabled, key)
            }
        }
    }

    @MainActor
    func testTextRoundTripOnAMixedLine() throws {
        _ = NSApplication.shared
        let fm = FileManager.default
        let suite = "NotchlineTests." + UUID().uuidString
        let folder = fm.temporaryDirectory.appendingPathComponent(suite)
        let defaults = try XCTUnwrap(UserDefaults(suiteName: suite))
        defaults.register(defaults: ClipboardWatcher.defaultPreferences)
        let pb = NSPasteboard.withUniqueName()
        let line = Line(defaults: defaults, pasteboard: pb)
        line.soundOn = false
        let watcher = ClipboardWatcher(pasteboard: pb, noteFolder: folder, defaults: defaults, isHanging: { url in
            line.items.contains { $0.url == url && !$0.falling }
        }, onCapture: { _ = line.hang($0, quietly: true) })
        defer {
            watcher.configure(images: false, text: false)
            pb.releaseGlobally()
            defaults.removePersistentDomain(forName: suite)
            try? fm.removeItem(at: folder)
        }
        func write(_ value: String, extra: NSPasteboard.PasteboardType? = nil) {
            let entry = NSPasteboardItem()
            entry.setString(value, forType: .string)
            if let extra { entry.setData(Data([1]), forType: extra) }
            pb.clearContents()
            XCTAssertTrue(pb.writeObjects([entry]))
            watcher.check()
        }

        write("already on clipboard")
        XCTAssertTrue(defaults.bool(forKey: "clipboardEnabled"))
        XCTAssertTrue(defaults.bool(forKey: ClipboardWatcher.textEnabledKey))
        watcher.configure(images: defaults.bool(forKey: "clipboardEnabled"),
                          text: defaults.bool(forKey: ClipboardWatcher.textEnabledKey))
        watcher.check()
        XCTAssertTrue(line.items.isEmpty)
        for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
            write("private", extra: .init(marker))
        }
        write("Finder selection", extra: .fileURL)
        write(" \t\r\n")
        write(String(repeating: "a", count: TextNote.maxBytes + 1))
        XCTAssertTrue(line.items.isEmpty)

        let original = "  初秋 🍂\r\n" + String(repeating: "e\u{301}\t段落\n", count: 550) + "  "
        write(original, extra: .png)
        let first = try XCTUnwrap(line.items.first)
        XCTAssertTrue(first.isText)
        let stock = try XCTUnwrap(TextNote(contentsOf: first.url)?.stock)
        XCTAssertNotEqual(stock, .parchment)
        XCTAssertEqual(try Data(contentsOf: first.url), Data(original.utf8))
        let attrs = try fm.attributesOfItem(atPath: first.url.path)
        XCTAssertEqual((attrs[.posixPermissions] as? NSNumber)?.intValue, 0o600)
        write(original)
        XCTAssertEqual(line.items.map(\.id), [first.id])

        // A second note makes the first one different from the watcher's last copy.
        watcher.randomPaperColors = false
        write("another clipping")
        let second = try XCTUnwrap(line.items.last)
        XCTAssertEqual(TextNote(contentsOf: second.url)?.stock, .parchment)
        line.copy(first.id)
        XCTAssertEqual(pb.string(forType: .string).map { Data($0.utf8) }, Data(original.utf8))
        XCTAssertNil(pb.data(forType: .fileURL))
        XCTAssertNil(pb.data(forType: .png))
        XCTAssertEqual(line.feedback?.kind, .copied)
        watcher.check()
        XCTAssertEqual(line.liveCount, 2)

        let png = try XCTUnwrap(first.thumb.tiffRepresentation.flatMap { NSBitmapImageRep(data: $0) }?
            .representation(using: .png, properties: [:]))
        let photo = folder.appendingPathComponent("photo.png")
        try png.write(to: photo)
        XCTAssertNotNil(line.hang(photo, quietly: true))
        let restored = Line(defaults: defaults, pasteboard: pb)
        XCTAssertEqual(restored.items.map(\.url), line.items.map(\.url))
        XCTAssertEqual(restored.items.map(\.isText), [true, true, false])
        XCTAssertEqual(TextNote(contentsOf: restored.items[0].url)?.stock, stock)
        XCTAssertEqual(TextNote(contentsOf: restored.items[1].url)?.stock, .parchment)
        line.discard(first.id, quietly: true)
        XCTAssertEqual(line.liveCount, 2)
        line.putBack()
        XCTAssertEqual(line.items.filter { !$0.falling }.map(\.url), restored.items.map(\.url))

        watcher.configure(images: true, text: false)
        write("text with an image fallback", extra: .png)
        XCTAssertEqual(line.liveCount, 3)
    }

    @MainActor
    func testGestureHintIsSavedAfterTheFirstTextPreview() throws {
        guard let screen = NSScreen.main else { throw XCTSkip("A display is needed for a hover preview") }
        let suite = "NotchlineTests." + UUID().uuidString
        let defaults = try XCTUnwrap(UserDefaults(suiteName: suite))
        let url = FileManager.default.temporaryDirectory.appendingPathComponent(suite + ".txt")
        defer {
            defaults.removePersistentDomain(forName: suite)
            try? FileManager.default.removeItem(at: url)
        }
        let item = Pegged(url: url, thumb: NSImage(size: NSSize(width: 144, height: 104)))
        let linePanel = LinePanel(content: NSView())
        linePanel.placeOnScreen(screen)
        let anchor = linePanel.frame
        let preview = HoverPreviewPanel(defaults: defaults)
        preview.show(item, anchor: anchor, below: linePanel)
        XCTAssertNil(preview.itemID)

        let text = "One line of text"
        try Data(text.utf8).write(to: url)
        preview.show(item, anchor: anchor, below: linePanel)
        XCTAssertEqual(preview.itemID, item.id)
        let firstHeight = preview.frame.height
        preview.hide()
        let next = HoverPreviewPanel(defaults: defaults)
        next.show(item, anchor: anchor, below: linePanel)
        XCTAssertEqual(next.itemID, item.id)
        XCTAssertLessThan(next.frame.height, firstHeight)
        next.hide()
    }

    @MainActor
    func testPreviewReflowsWithoutChangingTheHangingCardSize() throws {
        let short = TextNote("见字如面")
        let long = TextNote(String(repeating: "A paragraph with punctuation, 汉字 and emoji 🍂.\n", count: 150))
        let thumb = try XCTUnwrap(long.thumbnail(scale: 2))
        let oneLine = try XCTUnwrap(short.preview(width: 420, height: 360, scale: 2))
        let page = try XCTUnwrap(long.preview(width: 420, height: 360, scale: 2))
        XCTAssertEqual(thumb.size, CGSize(width: 144, height: 104))
        XCTAssertEqual(page.size.width, 420)
        XCTAssertGreaterThan(page.size.height, oneLine.size.height)
        XCTAssertLessThanOrEqual(page.size.height, 360)
        XCTAssertLessThan(long.excerpt.count, long.count)
    }
}
