import AppKit

/// Images and plain text have separate switches. Read only new copies, after
/// checking the types on every item for file promises and privacy markers.
@MainActor
final class ClipboardWatcher {
    nonisolated static let imagesEnabledKey = "clipboardEnabled"
    nonisolated static let textEnabledKey = "clipboardTextEnabled"
    static let defaultPreferences = [imagesEnabledKey: true, textEnabledKey: true, "randomPaperColors": true]

    static var imagesEnabled: Bool {
        get { UserDefaults.standard.bool(forKey: imagesEnabledKey) }
        set { UserDefaults.standard.set(newValue, forKey: imagesEnabledKey) }
    }
    static var textEnabled: Bool {
        get { UserDefaults.standard.bool(forKey: textEnabledKey) }
        set { UserDefaults.standard.set(newValue, forKey: textEnabledKey) }
    }

    static let fromLine = NSPasteboard.PasteboardType("local.notchline.from-line")
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .fileURL, .init("NSFilenamesPboardType"), .init("com.apple.pasteboard.promised-file-content-type"),
        .init("com.apple.pasteboard.promised-file-url"), fromLine,
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    private enum Kind: String { case image = "png", text = "txt" }
    private let isHanging: (URL) -> Bool
    private let onCapture: (URL) -> Void
    private let pasteboard: NSPasteboard
    private let noteFolder: URL
    private let defaults: UserDefaults
    private var lastStock: PaperStock?
    var randomPaperColors: Bool {
        get { defaults.bool(forKey: "randomPaperColors") }
        set { defaults.set(newValue, forKey: "randomPaperColors") }
    }
    private var timer: Timer?
    private var lastCount = 0
    private var countAtConfiguration = 0
    private var watchText = false
    private var watchImages = false
    private var last: [Kind: (data: Data, url: URL)] = [:]

    private static let maxImageBytes = 64 * 1024 * 1024
    nonisolated private static let maxPixels = 80_000_000

    init(pasteboard: NSPasteboard = .general, noteFolder: URL = TextNote.folder, defaults: UserDefaults = .standard,
         isHanging: @escaping (URL) -> Bool, onCapture: @escaping (URL) -> Void) {
        self.pasteboard = pasteboard
        self.noteFolder = noteFolder
        self.defaults = defaults
        self.isHanging = isHanging
        self.onCapture = onCapture
    }

    func configure(images: Bool, text: Bool) {
        // Start with the next copy, including after a change of settings.
        countAtConfiguration = pasteboard.changeCount
        lastCount = countAtConfiguration
        watchImages = images
        watchText = text
        if !images { last[.image] = nil }
        if !text { last[.text] = nil }
        guard images || text else {
            timer?.invalidate()
            timer = nil
            return
        }
        guard timer == nil else { return }
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func check() {
        let pb = pasteboard
        let count = pb.changeCount
        guard timer != nil, count != lastCount else { return }
        lastCount = count
        guard let items = pb.pasteboardItems, !items.isEmpty,
              items.allSatisfy({ Self.ignoredTypes.isDisjoint(with: $0.types) }) else { return }

        // Documents and spreadsheets often offer an image of the selection
        // alongside the string. Keep the string when text capture is enabled.
        if items.contains(where: { $0.types.contains(.string) }) {
            guard watchText, items.count == 1, let text = pb.string(forType: .string),
                  text.utf8.count <= TextNote.maxBytes, text.contains(where: { !$0.isWhitespace }),
                  pb.changeCount == count else { return }
            save(Data(text.utf8), as: .text)
            return
        }
        guard watchImages, let type = pb.availableType(from: [.png, .tiff]),
              let data = pb.data(forType: type), data.count <= Self.maxImageBytes,
              pb.changeCount == count else { return }
        DispatchQueue.global(qos: .userInitiated).async { [weak self] in
            let png = ClipboardWatcher.png(from: data, type: type)
            DispatchQueue.main.async {
                guard let self, let png, self.watchImages, self.countAtConfiguration != count,
                      self.pasteboard.changeCount == count else { return }
                self.save(png, as: .image)
            }
        }
    }

    nonisolated private static func png(from data: Data, type: NSPasteboard.PasteboardType) -> Data? {
        guard let rep = NSBitmapImageRep(data: data),
              rep.pixelsWide > 0, rep.pixelsHigh > 0,
              rep.pixelsWide <= maxPixels / rep.pixelsHigh else { return nil }
        return type == .png ? data : rep.representation(using: .png, properties: [:])
    }

    private func save(_ data: Data, as kind: Kind) {
        let fm = FileManager.default
        if let previous = last[kind], previous.data == data, fm.fileExists(atPath: previous.url.path) {
            if isHanging(previous.url) { return }
            if (try? Data(contentsOf: previous.url, options: .mappedIfSafe)) == data {
                onCapture(previous.url)
                return
            }
        }
        let folder = kind == .text ? noteFolder : Inbox.folder
        let stamp = DateFormatter()
        stamp.locale = Locale(identifier: "en_US_POSIX")
        stamp.dateFormat = "yyyy-MM-dd 'at' HH.mm.ss"
        let base = "Clipboard " + stamp.string(from: Date())
        var url = folder.appendingPathComponent(base).appendingPathExtension(kind.rawValue)
        var n = 2
        while fm.fileExists(atPath: url.path) {
            url = folder.appendingPathComponent("\(base) \(n)").appendingPathExtension(kind.rawValue)
            n += 1
        }
        do {
            try fm.createDirectory(at: folder, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
            try data.write(to: url, options: .atomic)
            try fm.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
            if kind == .text, randomPaperColors {
                let stock = PaperStock.randomColor(after: lastStock)
                stock.mark(url)
                lastStock = stock
            }
            last[kind] = (data, url)
            onCapture(url)
        } catch {
            try? fm.removeItem(at: url)
            log.error("Could not save a clipboard item: \(error.localizedDescription, privacy: .private)")
        }
    }
}
